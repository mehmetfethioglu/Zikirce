"""Generate `lib/features/recipes/data/builtin_recipe_r2_map.dart` for all 100 built-in recipes."""
import csv
import pathlib
import re
from difflib import SequenceMatcher

TR = str.maketrans("çğıöşüÇĞİIÖŞÜâîûÂÎÛ", "cgiosucgiiosuaiuaiu")
STOP_WORDS = {
    "klasik", "koy", "ev", "yapimi", "usulu", "pratik", "saglikli", "tam",
    "firin", "firinda", "sifa", "taze", "ozel", "anne", "lokanta",
    "geleneksel", "nefis", "harika", "kolay", "ekstra", "bol", "light", "fit",
}

MAPPING_CSV = pathlib.Path(r"G:\Drive'ım\Kilerce_Recipe_Covers\manifest_photo_v3_r2_mapping.csv")
CHECKPOINT_TXT = pathlib.Path(r"c:\Users\theak\Downloads\ym\r2_uploaded_keys.txt")
CATALOG_DIR = pathlib.Path(r"c:\Users\theak\source\repos\organicscore\lib\features\recipes\data")
OUT_DART = CATALOG_DIR / "builtin_recipe_r2_map.dart"


def fold(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", text.translate(TR).lower()).strip()


def load_r2_catalog() -> list[tuple[str, str, str, str, set[str]]]:
    uploaded = {
        line.strip()
        for line in CHECKPOINT_TXT.read_text(encoding="utf-8").splitlines()
        if line.strip()
    }
    rows = []
    with MAPPING_CSV.open("r", encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            rel = row["rel_path"].strip()
            if rel in uploaded:
                rf = fold(row["title"])
                rows.append((row["id"].strip(), rel, row["title"].strip(), rf, set(rf.split())))
    return rows


def parse_builtins() -> list[tuple[str, str]]:
    builtins = []
    for path in sorted(CATALOG_DIR.glob("catalog_*.dart")):
        txt = path.read_text(encoding="utf-8")
        for m in re.finditer(r"KilerRecipe\s*\((.*?)\n\s*\),", txt, re.S):
            blk = m.group(1)
            id_m = re.search(r"id:\s*'([^']+)'", blk)
            ti_m = re.search(r"title:\s*'([^']+)'", blk)
            if id_m and ti_m:
                builtins.append((id_m.group(1), ti_m.group(1)))
    return builtins


def best_match(title: str, r2_rows: list[tuple[str, str, str, str, set[str]]]) -> tuple[str, str, float]:
    bf = fold(title)
    btoks = [t for t in bf.split() if t not in STOP_WORDS and len(t) > 1]
    bset = set(btoks)
    best_row = None
    best_score = -1.0

    for _, rel, rtitle, rf, rset in r2_rows:
        if rf == bf:
            return (rel, rtitle, 10.0)
        if not bset:
            continue
        inter = len(bset & rset)
        if inter == 0:
            continue
        head_bonus = 0.35 if (btoks and btoks[-1] in rset) else 0.0
        jacc = inter / len(bset | rset)
        cov = inter / len(bset)
        seq = SequenceMatcher(None, bf, rf).ratio()
        score = cov * 0.55 + jacc * 0.25 + seq * 0.20 + head_bonus
        if score > best_score:
            best_score = score
            best_row = (rel, rtitle, score)

    if best_row is None or best_score < 0.45:
        raise RuntimeError(f"No valid R2 match found for '{title}' (best={best_row})")
    return best_row


def main() -> None:
    r2_rows = load_r2_catalog()
    builtins = parse_builtins()
    if len(builtins) != 100:
        raise RuntimeError(f"Expected 100 built-in recipes, parsed {len(builtins)}")

    lines = [
        "// GENERATED BY scripts/cloudflare/generate_builtin_r2_map.py — DO NOT HAND-EDIT.",
        "",
        "/// Verified Cloudflare R2 WebP object keys for all 100 offline starter recipes.",
        "const Map<String, String> kilerceBuiltinRecipeR2Paths = {",
    ]
    for bid, btitle in builtins:
        rel, rtitle, score = best_match(btitle, r2_rows)
        lines.append(f"  '{bid}': '{rel}', // {rtitle} ({score:.2f})")
    lines.append("};")
    lines.append("")

    OUT_DART.write_text("\n".join(lines), encoding="utf-8")
    print(f"BUILTIN_R2_MAP_OK count={len(builtins)} out={OUT_DART}")


if __name__ == "__main__":
    main()
